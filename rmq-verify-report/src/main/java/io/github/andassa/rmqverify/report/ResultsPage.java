package io.github.andassa.rmqverify.report;

import io.github.andassa.rmqverify.model.Anomaly;
import io.github.andassa.rmqverify.model.Verdict;
import io.github.andassa.rmqverify.model.VerdictStatus;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;

/**
 * Renders {@code RESULTS.md} from a matrix. Every number on the page comes from the {@code
 * report.json} files of real runs; nothing is typed by hand.
 *
 * @param generatedAt ISO-8601 generation time
 * @param gitCommit commit of the code that produced the runs
 * @param images container images used, by role
 * @param host description of the machine
 */
public record ResultsPage(
    String generatedAt, String gitCommit, Map<String, String> images, String host) {

  /** Copies the image map. */
  public ResultsPage {
    images = Map.copyOf(new java.util.TreeMap<>(images));
  }

  /**
   * Renders the page.
   *
   * @param matrix the runs
   * @return Markdown
   */
  public String markdown(Matrix matrix) {
    StringBuilder md = new StringBuilder("# Results\n\n");
    md.append("> Generated by `make bench` on ")
        .append(generatedAt)
        .append(" from commit `")
        .append(gitCommit)
        .append("`. Do not edit by hand: rerun `make bench`.\n\n");
    md.append("- Host: ").append(host).append('\n');
    md.append("- Runs: ").append(matrix.runs().size()).append(" (raw histories in `results/`)\n");
    new java.util.TreeMap<>(images)
        .forEach(
            (role, image) ->
                md.append("- Image ").append(role).append(": `").append(image).append("`\n"));
    appendMatrix(md, matrix);
    appendDetails(md, matrix);
    appendCounterexamples(md, matrix);
    md.append("\n## How to read these results\n\n");
    for (String line : limits()) {
      md.append("- ").append(line).append('\n');
    }
    return md.toString();
  }

  private static void appendMatrix(StringBuilder md, Matrix matrix) {
    md.append("\n## Matrix\n\n");
    md.append(
        "Each cell: runs with a violation / repetitions, then the totals over the repetitions.\n\n");
    md.append("| Scenario |");
    matrix.versions().forEach(v -> md.append(" RabbitMQ ").append(v).append(" |"));
    md.append("\n|---|");
    matrix.versions().forEach(v -> md.append("---|"));
    md.append('\n');
    for (String scenario : matrix.scenarios()) {
      md.append("| `").append(scenario).append("` |");
      for (String version : matrix.versions()) {
        md.append(' ')
            .append(matrix.cell(scenario, version).map(ResultsPage::summaryCell).orElse("not run"))
            .append(" |");
      }
      md.append('\n');
    }
  }

  private static void appendDetails(StringBuilder md, Matrix matrix) {
    md.append("\n## Details\n\n");
    md.append(
            "| Scenario | Version | Queue | Runs | Invalid | Unknown | Confirmed | Indeterminate | Lost | ")
        .append(
            "Missing after recovery | Unexpected duplicates | Order violations | Unexpected | Max recovery (s) | ")
        .append("Min success |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n");
    for (String scenario : matrix.scenarios()) {
      for (String version : matrix.versions()) {
        matrix
            .cell(scenario, version)
            .ifPresent(
                c ->
                    md.append(
                        String.format(
                            Locale.ROOT,
                            "| `%s` | %s | %s | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d | %.1f | %.1f%% |%n",
                            c.scenario(),
                            c.version(),
                            c.queueKind(),
                            c.runs(),
                            c.invalidRuns(),
                            c.unknownRuns(),
                            c.confirmed(),
                            c.indeterminate(),
                            c.lostConfirmed(),
                            c.missingAfterRecovery(),
                            c.unexpectedDuplicates(),
                            c.orderViolations(),
                            c.unexpectedMessages(),
                            c.maxRecoveryMs() / 1000,
                            100 * c.minSuccessRate())));
      }
    }
  }

  private static void appendCounterexamples(StringBuilder md, Matrix matrix) {
    md.append("\n## Counterexamples\n\n");
    boolean any = false;
    for (RunSummary run : matrix.runs()) {
      for (Verdict v : run.verdicts()) {
        Optional<Anomaly> first = v.anomalies().stream().filter(Anomaly::isViolation).findFirst();
        if (v.status() == VerdictStatus.INVALID && first.isPresent()) {
          any = true;
          md.append("- `")
              .append(run.scenario())
              .append("` on ")
              .append(run.rabbitmqVersion())
              .append(", run `")
              .append(run.runId())
              .append("`, ")
              .append(v.checker())
              .append(": ")
              .append(v.violationCount())
              .append(" violation(s), e.g. ")
              .append(first.get().description().replace("|", "\\|"))
              .append(" (operations ")
              .append(first.get().evidence())
              .append(")\n");
          break;
        }
      }
    }
    if (!any) {
      md.append("No violation was observed in these runs.\n");
    }
  }

  static String summaryCell(MatrixCell c) {
    return String.format(
        Locale.ROOT,
        "**%d/%d** invalid · lost %d · missing-after-recovery %d · dup %d · order %d · "
            + "max recovery %.1f s",
        c.invalidRuns(),
        c.runs(),
        c.lostConfirmed(),
        c.missingAfterRecovery(),
        c.unexpectedDuplicates(),
        c.orderViolations(),
        c.maxRecoveryMs() / 1000);
  }

  static List<String> limits() {
    return List.of(
        "A violation is a proof: its operations are in the archived history and `rmq-verify check` reproduces it.",
        "A clean cell is not a proof of correctness: it covers these plans, durations and repetitions only.",
        "The seed reproduces the fault plan and the workload, not the broker's timing; repetitions measure how often "
            + "an anomaly appears.",
        "The control scenario `classic-maxlength-control` drops confirmed messages on purpose (x-max-length with "
            + "drop-head): it shows that the checkers detect losses; it is not a RabbitMQ defect.",
        "Three nodes on one machine (Docker on a VM); the client reaches every node through Toxiproxy, which is a "
            + "stronger client than an application confined to one side of a partition.",
        "Indeterminate publishes (no confirm) are never counted as lost; see docs/METHODOLOGY.md.");
  }
}
